/// Mutable app-language state.
///
/// [code] always preserves the language chosen by the user. [locale] is kept
/// inside Flutter's built-in localization set so framework widgets never try to
/// load an unsupported Material localization and render a black error screen.
class L10nState extends ChangeNotifier {
  L10nState(String initialCode) : _code = _normalize(initialCode);

  String _code;

  String get code => _code;
  AppLanguage get language => languageByCode(_code);

  Locale get locale {
    return kMaterialSupportedLanguages.contains(_code)
        ? Locale(_code)
        : const Locale('en');
  }

  void setLanguage(String value) {
    final next = _normalize(value);
    if (next == _code) return;
    _code = next;
    L10nStateCode.current = next;
    notifyListeners();
  }

  String t(String key, [Map<String, Object> values = const {}]) {
    final selected = _strings[_code]?[key] ?? _strings['en']?[key] ?? key;
    return values.entries.fold<String>(
      selected,
      (text, entry) => text.replaceAll('{${entry.key}}', '${entry.value}'),
    );
  }

  static String _normalize(String value) {
    final code = value.trim().toLowerCase().split(RegExp('[-_]')).first;
    return appLanguages.any((language) => language.code == code) ? code : 'en';
  }
}

/// A lightweight bridge for code that cannot read a BuildContext.
abstract final class L10nStateCode {
  static String current = 'en';
}

